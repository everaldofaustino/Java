public class Intro18 {

    public static void main(String[] args) throws InterruptedException {

        // Faça um programa que inicia uma contagem regressiva a
        // partir de 10 até 1, imprimindo cada número na tela.

       for ( int i = 10; i>0; i-- ){

           System.out.println(i);
           Thread.sleep(500);

       }


    }
}




